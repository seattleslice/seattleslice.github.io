// Rebuilds js/sheet-backup.js from the live Google Sheet.
//
// Run it while the sheet is in a known-good state:
//
//   node tools/refresh-sheet-backup.js
//
// The backup holds each tab's raw value grid exactly as the Sheets API
// returns it, so a fallback read on the site runs through the same parsing
// as a live one (see readSheetTab in js/shared.js). Each tab has to come
// back with a healthy number of rows before anything is written - a run
// against a sheet that is currently broken refuses to touch the file, so
// the last good copy cannot be overwritten by the very breakage it is
// there to cover.

const fs = require('fs');
const path = require('path');

// The tabs the site reads, each with the column its parser keys rows on:
// loadSpeakers keeps rows that have a Name, loadSessions rows that have a
// Title. A new year means a new pair of tabs here.
const TABS = [
  { name: 'Speakers2026', keyColumn: 'Name' },
  { name: 'Sessions2026', keyColumn: 'Title' },
  { name: 'Speakers2025', keyColumn: 'Name' }
];

// Fewer usable rows than this and the tab is taken as broken, not as small.
const MIN_ROWS = 10;

const root = path.join(__dirname, '..');
const outFile = path.join(root, 'js', 'sheet-backup.js');

// The sheet id and API key live in js/shared.js; read them from there so
// there is only the one place they are ever changed.
const shared = fs.readFileSync(path.join(root, 'js', 'shared.js'), 'utf8');
const sheetId = (shared.match(/SPEAKERS_SHEET_ID\s*=\s*"([^"]+)"/) || [])[1];
const apiKey = (shared.match(/SPEAKERS_API_KEY\s*=\s*"([^"]+)"/) || [])[1];

if (!sheetId || !apiKey) {
  console.error('Could not read SPEAKERS_SHEET_ID / SPEAKERS_API_KEY from js/shared.js');
  process.exit(1);
}

async function fetchTab(tab) {
  const url = 'https://sheets.googleapis.com/v4/spreadsheets/' + sheetId +
    '/values/' + encodeURIComponent(tab.name) +
    '?dateTimeRenderOption=FORMATTED_STRING&majorDimension=ROWS' +
    '&valueRenderOption=FORMATTED_VALUE&key=' + apiKey;

  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(tab.name + ': the Sheets API answered ' + response.status);
  }

  const data = await response.json();
  const values = data.values;
  if (!Array.isArray(values) || !values.length) {
    throw new Error(tab.name + ': no rows came back - is the sheet broken right now?');
  }

  // Count the rows the site's own parser would keep: js/shared.js takes row 0
  // as the header and its loaders drop any row without the key column filled
  // in. A renamed or cleared header cell, or a stray row inserted above the
  // header, sails past a plain row count while parsing to nothing - and the
  // very breakage the backup exists to cover must not be able to overwrite
  // the last good copy of it.
  const keyAt = values[0].indexOf(tab.keyColumn);
  const kept = keyAt === -1 ? 0 :
    values.slice(1).filter(row => String(row[keyAt] || '').trim()).length;
  if (kept < MIN_ROWS) {
    throw new Error(tab.name + ': only ' + kept + ' rows carry a ' + tab.keyColumn +
      (keyAt === -1 ? ' (no such header cell in row 1)' : '') +
      ' - at least ' + MIN_ROWS + ' expected. Is the sheet broken right now?');
  }

  return values;
}

(async function() {
  const tabs = {};
  for (const tab of TABS) {
    tabs[tab.name] = await fetchTab(tab);
    console.log(tab.name + ': ' + tabs[tab.name].length + ' rows');
  }

  // The local date, not UTC's - an evening run should not stamp tomorrow
  const now = new Date();
  const savedAt = now.getFullYear() + '-' +
    String(now.getMonth() + 1).padStart(2, '0') + '-' +
    String(now.getDate()).padStart(2, '0');

  const lines = [];
  lines.push('// ===================== SHEET BACKUP =====================');
  lines.push('// A frozen copy of the public Google Sheet that powers the speakers and');
  lines.push('// sessions, held as the raw value grid of each tab exactly as the Sheets');
  lines.push('// API returns it, so a fallback runs through the same parsing as a live');
  lines.push('// read (see readSheetTab in js/shared.js). The live sheet always gets the');
  lines.push('// first try; this stands in only when that read errors, hangs past the');
  lines.push('// deadline, or comes back with one row or none - the shapes a bad sheet');
  lines.push('// edit takes.');
  lines.push('//');
  lines.push('// Generated by tools/refresh-sheet-backup.js. To refresh it once the');
  lines.push('// sheet is known-good after a change:  node tools/refresh-sheet-backup.js');
  lines.push('window.SHEET_BACKUP = {');
  lines.push("  savedAt: '" + savedAt + "',");
  lines.push('  tabs: {');

  TABS.forEach(function(tab, at) {
    const rows = tabs[tab.name];
    lines.push('    ' + JSON.stringify(tab.name) + ': [');
    rows.forEach(function(row, rowAt) {
      lines.push('      ' + JSON.stringify(row) +
        (rowAt < rows.length - 1 ? ',' : ''));
    });
    lines.push('    ]' + (at < TABS.length - 1 ? ',' : ''));
  });

  lines.push('  }');
  lines.push('};');
  lines.push('');

  fs.writeFileSync(outFile, lines.join('\n'), 'utf8');
  console.log('Wrote ' + path.relative(root, outFile) + ' (saved ' + savedAt + ')');
})().catch(function(err) {
  console.error(String(err && err.message || err));
  console.error('js/sheet-backup.js was left untouched.');
  process.exit(1);
});
